def _create_context_functions() -> None:
    """Readers for the RLS context.

    `STABLE` so the planner evaluates them once per query rather than once per row.
    With no context set they return NULL and an empty set, so no policy is ever
    satisfied: the failure is closed.
    """
    op.execute(
        """
        CREATE FUNCTION zenith_current_tenant() RETURNS uuid
        LANGUAGE sql STABLE AS $$
            SELECT nullif(current_setting('zenith.tenant_id', true), '')::uuid
        $$
        """
    )
    op.execute(
        """
        CREATE FUNCTION zenith_current_labels() RETURNS uuid[]
        LANGUAGE sql STABLE AS $$
            SELECT coalesce(
                string_to_array(nullif(current_setting('zenith.label_ids', true), ''), ',')::uuid[],
                '{}'::uuid[]
            )
        $$
        """
    )


