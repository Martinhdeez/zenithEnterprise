def _create_application_role() -> None:
    """Role the application connects as.

    It does not own the tables, which is why the policies apply to it. FORCE ROW
    LEVEL SECURITY is deliberately not used: the owner `zenith` must be able to
    create the first tenant from the CLI, when no context exists yet.

    The risk that opens is real and is covered by `core.database.verify_rls_active`:
    if someone points the application at the owner credentials, RLS would be inactive
    with no symptom at all. That is why startup checks it and refuses to serve.
    """
    op.execute(
        """
        DO $$
        BEGIN
            IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'zenith_app') THEN
                CREATE ROLE zenith_app NOLOGIN;
            END IF;
        END
        $$
        """
    )
    op.execute("GRANT USAGE ON SCHEMA public TO zenith_app")
    op.execute("GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO zenith_app")
    op.execute("GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO zenith_app")


